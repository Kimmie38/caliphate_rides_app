// Makes the app find its servers even when the phone's mobile network can't look them up.
//
// Some Nigerian carriers' DNS servers sometimes fail to find .ng addresses ("Unable to resolve host
// api.caliphaterides.com.ng"), while Google's and Cloudflare's find them fine. Users can't be asked
// to switch Airplane mode on and off, so the app handles it itself:
//
//  - Android: every connection (server calls, live updates, the map) first asks the phone as usual.
//    If that fails, it asks Cloudflare's encrypted DNS directly at 1.1.1.1 / 1.0.0.1 (no lookup
//    needed to reach them), and for our own domain, last of all, uses the server's known address.
//    HTTPS still checks the real caliphaterides.com.ng certificate, so this can't be spoofed.
//  - iPhone: Apple's built-in setting makes the app's lookups go through Cloudflare's encrypted
//    DNS (NWParameters.PrivacyContext.default.requireEncryptedNameResolution).
//
// Options: { domains: ["caliphaterides.com.ng"], serverAddresses: ["161.97.151.166"] }
const fs = require("fs");
const path = require("path");
const { withAppDelegate, withDangerousMod, withMainApplication } = require("expo/config-plugins");

const MARK = "CaliphateDns.install(this)";

function kotlin(pkg, domains, addresses) {
  const list = (xs) => xs.map((x) => JSON.stringify(x)).join(", ");
  return `package ${pkg}

import android.content.Context
import android.util.Log
import com.facebook.react.modules.network.OkHttpClientFactory
import com.facebook.react.modules.network.OkHttpClientProvider
import java.net.InetAddress
import java.net.UnknownHostException
import java.util.concurrent.ConcurrentHashMap
import java.util.concurrent.TimeUnit
import okhttp3.Dispatcher
import okhttp3.Dns
import okhttp3.OkHttpClient
import okhttp3.Request
import org.json.JSONObject

/**
 * Finds server addresses even when the mobile network's DNS can't (generated by
 * plugins/withReliableDns.js; edit it there). Order: the phone's normal lookup, then Cloudflare's
 * encrypted DNS reached by its fixed addresses, then, for our own domain, the server's known address.
 */
object CaliphateDns : Dns {
  private const val TAG = "CaliphateDns"
  private val OWN_DOMAINS = arrayOf(${list(domains)})
  private val OWN_SERVER = arrayOf(${list(addresses)})
  // Cloudflare answers JSON at its fixed addresses (Google's fixed addresses only redirect to a name).
  private val SECURE_DNS = arrayOf("https://1.1.1.1/dns-query", "https://1.0.0.1/dns-query")
  private val IPV4 = Regex("^\\\\d{1,3}(\\\\.\\\\d{1,3}){3}$")
  private val HOSTNAME = Regex("^[A-Za-z0-9.-]{1,253}$")

  // After the phone's lookup fails for a name, skip it for a minute (each failure can take seconds).
  private const val SKIP_PHONE_MS = 60_000L
  // When the encrypted lookup fails too (no internet at all), don't retry it for a few seconds.
  private const val SKIP_SECURE_MS = 15_000L

  private class Found(val addresses: List<InetAddress>, val until: Long)
  private val found = ConcurrentHashMap<String, Found>()
  private val phoneFailedAt = ConcurrentHashMap<String, Long>()
  @Volatile private var secureFailedAt = 0L

  private val secureClient: OkHttpClient by lazy {
    OkHttpClient.Builder()
      .connectTimeout(2, TimeUnit.SECONDS)
      .readTimeout(2, TimeUnit.SECONDS)
      .callTimeout(3, TimeUnit.SECONDS)
      .followRedirects(false)
      .build()
  }

  /** Called first thing when the app starts, before any connection is made. */
  @JvmStatic
  fun install(context: Context) {
    val appContext = context.applicationContext
    // Server calls (fetch) and live updates (WebSocket) all use this client.
    OkHttpClientProvider.setOkHttpClientFactory(OkHttpClientFactory {
      OkHttpClientProvider.createClientBuilder(appContext).dns(CaliphateDns).build()
    })
    // The map (MapLibre) loads tiles, fonts and styles with its own client.
    try {
      val dispatcher = Dispatcher().apply { maxRequestsPerHost = 20 }
      val mapClient = OkHttpClient.Builder().dispatcher(dispatcher).dns(CaliphateDns).build()
      Class.forName("org.maplibre.android.module.http.HttpRequestUtil")
        .getMethod("setOkHttpClient", OkHttpClient::class.java)
        .invoke(null, mapClient)
    } catch (e: Throwable) {
      Log.w(TAG, "map client unchanged: " + e.message)
    }
  }

  override fun lookup(hostname: String): List<InetAddress> {
    val now = System.currentTimeMillis()
    var phoneError: UnknownHostException? = null
    val failedAt = phoneFailedAt[hostname]
    if (failedAt == null || now - failedAt > SKIP_PHONE_MS) {
      try {
        val list = Dns.SYSTEM.lookup(hostname)
        if (list.isNotEmpty()) {
          phoneFailedAt.remove(hostname)
          return list
        }
      } catch (e: UnknownHostException) {
        phoneError = e
      }
      phoneFailedAt[hostname] = now
    }

    found[hostname]?.let { if (it.until > now) return it.addresses }
    if (now - secureFailedAt > SKIP_SECURE_MS) {
      val secure = askSecureDns(hostname)
      if (secure != null) return secure
      secureFailedAt = now
    }
    if (isOwn(hostname) && OWN_SERVER.isNotEmpty()) {
      Log.w(TAG, "using the known server address for " + hostname)
      return OWN_SERVER.map { InetAddress.getByName(it) }
    }
    found[hostname]?.let { return it.addresses } // out of date, but better than nothing
    throw phoneError ?: UnknownHostException(hostname)
  }

  private fun isOwn(host: String): Boolean = OWN_DOMAINS.any { host == it || host.endsWith(".$it") }

  private fun askSecureDns(hostname: String): List<InetAddress>? {
    if (!HOSTNAME.matches(hostname) || IPV4.matches(hostname)) return null
    for (base in SECURE_DNS) {
      try {
        val request = Request.Builder()
          .url("$base?type=A&name=$hostname")
          .header("Accept", "application/dns-json")
          .build()
        val list = secureClient.newCall(request).execute().use { response ->
          if (!response.isSuccessful) null else parseAnswer(hostname, response.body?.string())
        }
        if (list != null) return list
      } catch (e: Exception) {
        Log.w(TAG, "encrypted lookup via " + base + " failed: " + e.message)
      }
    }
    return null
  }

  private fun parseAnswer(hostname: String, body: String?): List<InetAddress>? {
    if (body == null) return null
    val json = JSONObject(body)
    if (json.optInt("Status", -1) != 0) return null
    val answers = json.optJSONArray("Answer") ?: return null
    val list = ArrayList<InetAddress>()
    var ttl = 3600
    for (i in 0 until answers.length()) {
      val answer = answers.optJSONObject(i) ?: continue
      if (answer.optInt("type") != 1) continue // A records only
      val ip = answer.optString("data")
      if (!IPV4.matches(ip)) continue
      list.add(InetAddress.getByName(ip)) // a literal address: no lookup happens here
      ttl = minOf(ttl, answer.optInt("TTL", 300))
    }
    if (list.isEmpty()) return null
    found[hostname] = Found(list, System.currentTimeMillis() + maxOf(60, ttl) * 1000L)
    return list
  }
}
`;
}

const SWIFT = `
    // Look up our servers with Cloudflare's encrypted DNS, so a mobile network whose DNS can't find
    // .ng addresses doesn't stop the app (plugins/withReliableDns.js).
    if let resolver = URL(string: "https://cloudflare-dns.com/dns-query") {
      NWParameters.PrivacyContext.default.requireEncryptedNameResolution(
        true,
        fallbackResolver: .https(resolver, serverAddresses: [
          .hostPort(host: "1.1.1.1", port: 443),
          .hostPort(host: "1.0.0.1", port: 443),
        ])
      )
    }
`;

module.exports = function withReliableDns(config, { domains = [], serverAddresses = [] } = {}) {
  // Android: write CaliphateDns.kt next to MainApplication.kt ...
  config = withDangerousMod(config, ["android", async (c) => {
    const pkg = c.android?.package;
    if (!pkg) throw new Error("withReliableDns: android.package is missing in the app config.");
    const dir = path.join(c.modRequest.platformProjectRoot, "app", "src", "main", "java", ...pkg.split("."));
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, "CaliphateDns.kt"), kotlin(pkg, domains, serverAddresses));
    return c;
  }]);

  // ... and switch it on first thing in MainApplication.onCreate.
  config = withMainApplication(config, (c) => {
    let src = c.modResults.contents;
    if (!src.includes(MARK)) {
      src = src.replace(/(override fun onCreate\(\) \{\n\s*super\.onCreate\(\)\n)/, `$1    ${MARK} // find our servers even when the mobile network's DNS can't\n`);
    }
    if (!src.includes(MARK)) throw new Error("withReliableDns: couldn't find onCreate() in MainApplication.kt.");
    c.modResults.contents = src;
    return c;
  });

  // iPhone: encrypted lookups for every connection the app makes.
  config = withAppDelegate(config, (c) => {
    if (c.modResults.language !== "swift") throw new Error("withReliableDns: expected a Swift AppDelegate.");
    let src = c.modResults.contents;
    if (!/^import Network$/m.test(src)) src = src.replace(/^import React$/m, "import Network\nimport React");
    if (!src.includes("requireEncryptedNameResolution")) {
      src = src.replace(/(didFinishLaunchingWithOptions launchOptions:[^{]*\{\n)/, `$1${SWIFT}`);
    }
    if (!src.includes("requireEncryptedNameResolution") || !/^import Network$/m.test(src)) {
      throw new Error("withReliableDns: couldn't add encrypted DNS to AppDelegate.swift.");
    }
    c.modResults.contents = src;
    return c;
  });
  return config;
};
